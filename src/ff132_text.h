// Everything the mod draws, in both languages; ui_text() picks the column.
//
// Constraints -- each corrupts a line rather than merely looking wrong:
//   1. A Japanese string must carry the same %-conversions as its English one: same count, same
//      types, same ORDER (snprintf has no positional form here, so reword rather than reorder).
//   2. One entry per line, UTF-8 without BOM: the Japanese column reaches the font through
//      MultiByteToWideChar(CP_UTF8, ...).
//   3. The English column is ASCII only: it is also what is drawn when there is no Japanese font.
// Not here: text written INTO a save file (the world label, the note), which is cp932 file content.

